// The poses drawn in the pixel workshop (the "Taller de Clawd" artifact), as
// it exports them: 24 pixels across by 12 down over the band's four rows,
// two across and three down to a cell, drawn in sextants; Clawd's front-on
// body four pixels in. A cell whose halves differ is kept in quarters, two
// pixels down, among a shot's `cells`: Clawd's shape is the one it had when
// every cell was in quarters, and what it does around itself has the finer
// grid to move in. Each letter is a color (`PIXEL` in desks.ts): O the body,
// D its shade, K an eye, N a book's cover, P its pages, W white, B the
// headphones, U a mug, M coffee, E an ember, Y gold, S smoke and steam, R
// red; `.` is empty. Drawn facing right: the director mirrors them going
// left. Each fits the terminal's cells, two colors to a full cell and one to
// a cell part empty.

// A drawing and the ticks it holds. A `busy` one is mid-action (a sip, a
// puff): its scene does not give way during it. `eyes` draws each eye's cell
// as a glyph the pixels cannot: smiling (^) or shut (▁)
export type Eyes = 'joy' | 'shut'
// One cell of a drawing on a grid of its own, over the drawing's pixels: `x`
// and `y` count cells. Quarters are two rows of two pixels, `px`: what keeps
// an eye half a cell tall in a drawing whose other cells are sextants.
// Eighths are one edge: the cell filled with `color` from a side, `level`
// eighths of the way, over `back` or nothing. An edge an eighth at a time is
// what moves smoothly: a breath, a puff of smoke
export type Edge = 'bottom' | 'top' | 'left' | 'right'
export type GridCell =
  | { x: number; y: number; grid: 'quarters'; px: readonly string[] }
  | { x: number; y: number; grid: 'eighths'; from: Edge; level: number; color: string; back?: string }
export type Shot = { ticks: number; px: readonly string[]; busy?: true; eyes?: Eyes; cells?: readonly GridCell[] }

// The cells of a drawing mirrored with it, `columns` cells wide
export const mirroredCells = (cells: readonly GridCell[], columns = 12): GridCell[] =>
  cells.map(cell => {
    const x = columns - 1 - cell.x
    if (cell.grid === 'quarters') return { ...cell, x, px: cell.px.map(row => [...row].reverse().join('')) }
    return { ...cell, x, from: cell.from === 'left' ? 'right' : cell.from === 'right' ? 'left' : cell.from }
  })

// The ticks one pass of a loop of shots takes
export const loopTicks = (shots: readonly Shot[]) => shots.reduce((n, shot) => n + shot.ticks, 0)

// The shot `s` ticks into a loop of them
export function shotAt(shots: readonly Shot[], s: number): Shot {
  let k = s % loopTicks(shots)
  for (const shot of shots) {
    if (k < shot.ticks) return shot
    k -= shot.ticks
  }
  return shots[0]!
}

